// Helper: returns a YYYY-MM-DD date string relative to today (offset in days)
export const currentDate = (offsetDays = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

